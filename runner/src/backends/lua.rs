const HARNESS: &str = r#"-- Generated by `learn generate`. A tiny test harness using pcall and a deep
-- table compare.

local H = {}
H.__index = H

function H.new()
  return setmetatable({ failed = 0 }, H)
end

local function deep_equal(a, b)
  if type(a) ~= "table" or type(b) ~= "table" then
    return a == b
  end
  for k, v in pairs(a) do
    if not deep_equal(v, b[k]) then return false end
  end
  for k in pairs(b) do
    if a[k] == nil then return false end
  end
  return true
end

local function show(v)
  if type(v) == "string" then return string.format("%q", v) end
  if type(v) ~= "table" then return tostring(v) end
  local keys = {}
  for k in pairs(v) do keys[#keys + 1] = k end
  table.sort(keys, function(x, y) return tostring(x) < tostring(y) end)
  local parts = {}
  local is_list = #keys == #v
  for _, k in ipairs(keys) do
    if is_list then
      parts[#parts + 1] = show(v[k])
    else
      parts[#parts + 1] = "[" .. show(k) .. "] = " .. show(v[k])
    end
  end
  return "{" .. table.concat(parts, ", ") .. "}"
end

function H:fail(name, why)
  self.failed = self.failed + 1
  print("not ok " .. name .. " - " .. why)
end

--- The function must return `expected` (extra return values are ignored).
function H:equals(name, fn, expected)
  local ok, result = pcall(fn)
  if not ok then
    self:fail(name, "raised an error: " .. tostring(result))
  elseif deep_equal(result, expected) then
    print("ok " .. name)
  else
    self:fail(name, "expected " .. show(expected) .. ", got " .. show(result))
  end
end

--- The function must return nil plus an error value. Raising doesn't count.
function H:returns_error(name, fn)
  local ok, result, err = pcall(fn)
  if not ok then
    self:fail(name, "raised an error instead of returning nil, err: " .. tostring(result))
  elseif result == nil and err ~= nil then
    print("ok " .. name)
  else
    self:fail(name, "expected nil plus an error, got " .. show(result) .. ", " .. show(err))
  end
end

--- Inside scenario(): stop the case with a message when a check fails.
function H.expect(actual, expected, what)
  if not deep_equal(actual, expected) then
    error({ message = what .. ": expected " .. show(expected) .. ", got " .. show(actual) }, 0)
  end
end

function H.check(ok, message)
  if not ok then error({ message = message }, 0) end
end

--- A case made of several checks (H.expect / H.check).
function H:scenario(name, fn)
  local ok, err = pcall(fn)
  if ok then
    print("ok " .. name)
  elseif type(err) == "table" and err.message then
    self:fail(name, err.message)
  else
    self:fail(name, "raised an error: " .. tostring(err))
  end
end

function H:finish()
  os.exit(self.failed == 0 and 0 or 1)
end

return H
"#;

const CLOCK: &str = r#"--- Provided, don't change: a virtual clock. Lua has no threads or sleep, so
--- time is counted in ticks. Call M.tick() once per scheduling round.
M.clock = { now = 0 }

function M.tick()
  M.clock.now = M.clock.now + 1
end

--- Provided, don't change: a slow task. It must run inside a coroutine: it
--- yields until `ms` ticks have passed, then returns `ms`.
function M.task(ms)
  local done_at = M.clock.now + ms
  while M.clock.now < done_at do
    coroutine.yield()
  end
  return ms
end

"#;

fn str_lit(s: &str) -> String {
    // Lua escapes control bytes as \ddd.
    format!("\"{}\"", escape(s, |c| format!("\\{c:03}"), &[]))
}

impl Lua {
    fn module(spec: &Spec) -> String {
        naming::snake(&spec.slug)
    }

    fn type_defs(&self, spec: &Spec) -> String {
        let mut s = String::new();
        for d in &spec.types {
            let name = naming::pascal(&d.name);
            match d.kind {
                DefKind::Interface => {
                    s.push_str(&format!("--- @class {name}\n"));
                    for m in &d.methods {
                        let ps: Vec<String> = std::iter::once("self".to_string())
                            .chain(m.params.iter().map(|p| format!("{}: {}", p.name, self.type_name(spec, &p.ty, true))))
                            .collect();
                        s.push_str(&format!(
                            "--- @field {} fun({}): {}\n",
                            naming::snake(&m.name),
                            ps.join(", "),
                            self.type_name(spec, &m.returns, false)
                        ));
                    }
                    s.push('\n');
                }
                DefKind::Record => {
                    s.push_str(&format!("--- A plain table.\n--- @class {name}\n"));
                    for f in &d.fields {
                        s.push_str(&format!("--- @field {} {}\n", naming::snake(&f.name), self.type_name(spec, &f.ty, false)));
                    }
                    s.push('\n');
                }
                DefKind::Class => {
                    let parent = d.implements.first().map(|i| format!(": {}", naming::pascal(i))).unwrap_or_default();
                    s.push_str(&format!("--- @class {name}{parent}\n"));
                    for f in &d.fields {
                        s.push_str(&format!("--- @field {} {}\n", naming::snake(&f.name), self.type_name(spec, &f.ty, false)));
                    }
                    let fields: Vec<String> = d.fields.iter().map(|f| naming::snake(&f.name)).collect();
                    let init: Vec<String> = fields.iter().map(|f| format!("{f} = {f}")).collect();
                    s.push_str(&format!(
                        "M.{name} = {{}}\nM.{name}.__index = M.{name}\n\n--- @return {name}\nfunction M.{name}.new({})\n  return setmetatable({{ {} }}, M.{name})\nend\n\n",
                        fields.join(", "),
                        init.join(", ")
                    ));
                    for m in &d.methods {
                        let ps: Vec<&str> = m.params.iter().map(|p| p.name.as_str()).collect();
                        let mname = naming::snake(&m.name);
                        s.push_str(&format!(
                            "function M.{name}:{mname}({})\n  error(\"{}\")\nend\n\n",
                            ps.join(", "),
                            stub_message(&format!("{name}:{mname}"))
                        ));
                    }
                }
            }
        }
        s
    }

    fn fn_stub(&self, spec: &Spec, f: &Function) -> String {
        let mut s = doc("--- ", &f.summary);
        for p in &f.params {
            s.push_str(&format!("--- @param {} {}\n", p.name, self.type_name(spec, &p.ty, true)));
        }
        if f.fallible {
            s.push_str(&format!(
                "--- @return {}|nil result\n--- @return string|nil err  return nil, \"message\" for invalid input; don't raise\n",
                self.type_name(spec, &f.returns, false)
            ));
        } else {
            s.push_str(&format!("--- @return {}\n", self.type_name(spec, &f.returns, false)));
        }
        s.push_str(&format!("{}\n  error(\"{}\")\nend\n", self.signature(spec, f), stub_message(&self.function_name(f))));
        s
    }

    fn call(&self, spec: &Spec, f: &Function, input: &[Value]) -> String {
        let table = f.module.as_deref().map(naming::snake).unwrap_or_else(|| "M".into());
        format!("{table}.{}({})", self.function_name(f), render_args(&f.params, input, |v, t| self.literal(spec, v, t)))
    }
}

impl Backend for Lua {
    fn id(&self) -> &'static str {
        "lua"
    }
    fn name(&self) -> &'static str {
        "Lua"
    }
    fn fence(&self) -> &'static str {
        "lua"
    }
    fn tool(&self) -> &'static Tool {
        &TOOL
    }

    fn function_name(&self, f: &Function) -> String {
        naming::snake(&f.name)
    }

    /// LuaLS annotation types (documentation only).
    fn type_name(&self, spec: &Spec, ty: &Type, _param: bool) -> String {
        match ty {
            Type::Int => "integer".into(),
            Type::Bool => "boolean".into(),
            Type::Str => "string".into(),
            Type::List(t) => format!("{}[]", self.type_name(spec, t, false)),
            Type::Map(t) => format!("table<string, {}>", self.type_name(spec, t, false)),
            Type::Named(n) => naming::pascal(n),
            Type::Fn(ps, r) => {
                let ps: Vec<String> =
                    ps.iter().enumerate().map(|(i, t)| format!("a{i}: {}", self.type_name(spec, t, false))).collect();
                format!("fun({}): {}", ps.join(", "), self.type_name(spec, r, false))
            }
        }
    }

    fn literal(&self, spec: &Spec, value: &Value, ty: &Type) -> String {
        match (ty, value) {
            (Type::Int, Value::Number(n)) => n.to_string(),
            (Type::Bool, Value::Bool(b)) => b.to_string(),
            (Type::Str, Value::String(s)) => str_lit(s),
            (Type::List(t), Value::Array(items)) => {
                let parts: Vec<String> = items.iter().map(|v| self.literal(spec, v, t)).collect();
                format!("{{{}}}", parts.join(", "))
            }
            (Type::Map(t), Value::Object(m)) => {
                let parts: Vec<String> =
                    m.iter().map(|(k, v)| format!("[{}] = {}", str_lit(k), self.literal(spec, v, t))).collect();
                format!("{{{}}}", parts.join(", "))
            }
            (Type::Named(n), _) => {
                let def = def_of(spec, n, value);
                let fields = field_values(def, value);
                if def.kind == DefKind::Class {
                    let args: Vec<String> = fields.into_iter().map(|(f, v)| self.literal(spec, v, &f.ty)).collect();
                    format!("M.{}.new({})", naming::pascal(&def.name), args.join(", "))
                } else {
                    let parts: Vec<String> = fields
                        .into_iter()
                        .map(|(f, v)| format!("{} = {}", naming::snake(&f.name), self.literal(spec, v, &f.ty)))
                        .collect();
                    format!("{{ {} }}", parts.join(", "))
                }
            }
            _ => unreachable!("spec values are validated against their types"),
        }
    }

    fn signature(&self, _spec: &Spec, f: &Function) -> String {
        let params: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        format!("function M.{}({})", self.function_name(f), params.join(", "))
    }

    fn stub_path(&self, spec: &Spec) -> PathBuf {
        PathBuf::from(&spec.slug).join(format!("{}.lua", Self::module(spec)))
    }

    fn module_path(&self, spec: &Spec, module: &str) -> PathBuf {
        PathBuf::from(&spec.slug).join(format!("{}.lua", naming::snake(module)))
    }

    fn stubs(&self, spec: &Spec) -> Vec<(PathBuf, String)> {
        let mut main = String::from("local M = {}\n\n");
        if spec.concurrency {
            main.push_str(CLOCK);
        }
        main.push_str(&self.type_defs(spec));
        main.push_str(&self.fn_stub(spec, &spec.main));
        main.push_str("\nreturn M\n");
        let mut out = vec![(self.stub_path(spec), main)];
        for m in spec.modules() {
            let mut s = String::from("local M = {}\n");
            for f in spec.helpers.iter().filter(|h| h.module.as_deref() == Some(m)) {
                s.push('\n');
                s.push_str(&self.fn_stub(spec, f));
            }
            s.push_str("\nreturn M\n");
            out.push((self.module_path(spec, m), s));
        }
        out
    }

    fn tests(&self, spec: &Spec) -> Vec<(PathBuf, String)> {
        let module = Self::module(spec);
        let mut s = header("--", spec, &format!("{module}.lua"));
        s.push_str(
            "\n-- Resolve modules relative to this file, wherever lua is started from.\n\
             local dir = (arg and arg[0] or \"\"):match(\"^(.*)[/\\\\]\") or \".\"\n\
             package.path = dir .. \"/?.lua;\" .. dir .. \"/../?.lua;\" .. package.path\n\n",
        );
        s.push_str("local H = require(\"harness\")\n");
        for m in spec.modules() {
            s.push_str(&format!("local {0} = require(\"{0}\")\n", naming::snake(m)));
        }
        s.push_str(&format!("local M = require(\"{module}\")\n\nlocal t = H.new()\n"));

        for (f, case) in spec.cases() {
            let name = case_name(case);
            match &case.kind {
                CaseKind::Call { input, outcome } => {
                    let call = self.call(spec, f, input);
                    match outcome {
                        Outcome::Value(v) if spec.concurrency => {
                            let t = timing(input);
                            s.push_str(&format!(
                                "t:scenario(\"{name}\", function()\n  M.clock.now = 0\n  local got = {call}\n  H.expect(got, {}, \"result\")\n  local ticks = M.clock.now\n  H.check(ticks >= {}, \"the clock only reached \" .. ticks .. \" ticks, but the slowest task needs {}: run every task to completion\")\n  H.check(ticks <= {}, \"took \" .. ticks .. \" ticks: resume the coroutines round-robin so it takes about {} ticks, not {}\")\nend)\n",
                                self.literal(spec, v, &f.returns),
                                t.max, t.max, t.max + 1, t.max, t.sum
                            ));
                        }
                        Outcome::Value(v) if kept_inputs(spec, f).iter().any(Option::is_some) => {
                            // Tables are shared with the caller: check the function left them alone.
                            let kept = kept_inputs(spec, f);
                            let (args, vars) =
                                render_kept_args(f, input, &kept, |v, t| self.literal(spec, v, t), naming::snake);
                            s.push_str(&format!("t:scenario(\"{name}\", function()\n"));
                            for (var, lit, _) in &vars {
                                s.push_str(&format!("  local {var} = {lit}\n"));
                            }
                            s.push_str(&format!(
                                "  H.expect(M.{}({args}), {}, \"result\")\n",
                                self.function_name(f),
                                self.literal(spec, v, &f.returns)
                            ));
                            for (var, lit, kind) in &vars {
                                s.push_str(&format!("  H.expect({var}, {lit}, \"the input {kind} was modified\")\n"));
                            }
                            s.push_str("end)\n");
                        }
                        Outcome::Value(v) => s.push_str(&format!(
                            "t:equals(\"{name}\", function() return {call} end, {})\n",
                            self.literal(spec, v, &f.returns)
                        )),
                        Outcome::Error => {
                            s.push_str(&format!("t:returns_error(\"{name}\", function() return {call} end)\n"))
                        }
                    }
                }
                CaseKind::Scenario { create, steps } => {
                    s.push_str(&format!("t:scenario(\"{name}\", function()\n"));
                    for (i, args) in create.iter().enumerate() {
                        s.push_str(&format!("  local v{i} = {}\n", self.call(spec, f, args)));
                    }
                    let Type::Fn(ps, ret) = &f.returns else { unreachable!() };
                    for (n, step) in steps.iter().enumerate() {
                        let args: Vec<String> = step.input.iter().zip(ps).map(|(v, t)| self.literal(spec, v, t)).collect();
                        s.push_str(&format!(
                            "  H.expect(v{}({}), {}, \"{}\")\n",
                            step.on,
                            args.join(", "),
                            self.literal(spec, &step.expected, ret),
                            step_label(n + 1, step.on, create.len())
                        ));
                    }
                    s.push_str("end)\n");
                }
            }
        }
        s.push_str("t:finish()\n");
        vec![(PathBuf::from(&spec.slug).join(format!("{module}_test.lua")), s)]
    }

    fn shared(&self, _specs: &[Spec]) -> Vec<(PathBuf, String)> {
        vec![(PathBuf::from("harness.lua"), HARNESS.to_string())]
    }

    fn command(&self, spec: &Spec, tool: &Found, track_dir: &Path) -> Invocation {
        Invocation::new(&tool.path, track_dir)
            .args([format!("{}/{}_test.lua", spec.slug, Self::module(spec))])
            .timeout(Duration::from_secs(60))
    }

    fn parse_results(&self, output: &str) -> Vec<(usize, bool)> {
        parse_tap(output)
    }

    fn check_tool(&self, tool: &Found) -> Option<String> {
        (!tool.version.contains("5.4")).then(|| {
            format!(
                "the track is written for Lua 5.4 but found `{}`. Most exercises still work, but integer division (//) and math.type don't exist before 5.3",
                tool.version
            )
        })
    }
}
