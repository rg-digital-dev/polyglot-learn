//! PHP: plain `php` with a tiny generated assert harness. No Composer.
//! Helper modules are namespaced files; concurrency uses Fibers on a virtual clock.

use std::path::{Path, PathBuf};
use std::time::Duration;

use serde_json::Value;

use super::{case_name, def_of, doc, escape, field_values, header, hex_escape, parse_tap, render_args, step_label, stub_message, timing, Backend};
use crate::naming;
use crate::spec::{CaseKind, DefKind, Function, Method, Outcome, Param, Spec, Type};
use crate::toolchain::{parse_version, Found, Invocation, Tool};

pub struct Php;

static TOOL: Tool = Tool {
    label: "php",
    candidates: &["php", "php8.5", "php8.4", "php8.3", "php8.2", "php8.1", "/opt/homebrew/bin/php", "C:/php/php.exe"],
    version_args: &["--version"],
    prefer: None,
};

const HARNESS: &str = r#"<?php
// Generated by `learn generate`. A tiny test harness: no Composer, no PHPUnit.

declare(strict_types=1);

final class Harness
{
    private int $failed = 0;

    /** Maps compare regardless of key order; lists keep their order; objects compare by class and properties. */
    private static function normalize(mixed $value): mixed
    {
        if (is_object($value) && !($value instanceof \Closure)) {
            return ['__class' => get_class($value)] + self::normalize(get_object_vars($value));
        }
        if (!is_array($value)) {
            return $value;
        }
        if (!array_is_list($value)) {
            ksort($value, SORT_STRING);
        }
        return array_map([self::class, 'normalize'], $value);
    }

    public static function show(mixed $value): string
    {
        return json_encode(self::normalize($value), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) ?: var_export($value, true);
    }

    private static function isStub(\Throwable $e): bool
    {
        return str_starts_with($e->getMessage(), 'TODO: implement');
    }

    /** Used inside scenario(): stop the case with a message when the check fails. */
    public static function expect(mixed $actual, mixed $expected, string $what): void
    {
        if (self::normalize($actual) !== self::normalize($expected)) {
            throw new \UnexpectedValueException("$what: expected " . self::show($expected) . ', got ' . self::show($actual));
        }
    }

    public static function check(bool $ok, string $message): void
    {
        if (!$ok) {
            throw new \UnexpectedValueException($message);
        }
    }

    public function equals(string $name, callable $fn, mixed $expected): void
    {
        try {
            $actual = $fn();
        } catch (\Throwable $e) {
            $this->fail($name, 'threw ' . get_class($e) . ': ' . $e->getMessage());
            return;
        }
        if (self::normalize($actual) === self::normalize($expected)) {
            echo "ok $name\n";
        } else {
            $this->fail($name, 'expected ' . self::show($expected) . ', got ' . self::show($actual));
        }
    }

    public function throws(string $name, callable $fn): void
    {
        try {
            $actual = $fn();
        } catch (\Throwable $e) {
            if (self::isStub($e)) {
                $this->fail($name, 'still the stub: ' . $e->getMessage());
            } else {
                echo "ok $name\n";
            }
            return;
        }
        $this->fail($name, 'expected an exception, got ' . self::show($actual));
    }

    /** A case made of several checks (Harness::expect / Harness::check). */
    public function scenario(string $name, callable $fn): void
    {
        try {
            $fn();
            echo "ok $name\n";
        } catch (\Throwable $e) {
            $this->fail($name, $e->getMessage());
        }
    }

    private function fail(string $name, string $why): void
    {
        $this->failed++;
        echo "not ok $name - $why\n";
    }

    public function finish(): never
    {
        exit($this->failed === 0 ? 0 : 1);
    }
}
"#;

const CLOCK: &str = r#"/**
 * Provided, don't change: a virtual clock. Plain PHP has no threads, so time
 * is counted in ticks. Call Clock::tick() once per scheduling round.
 */
final class Clock
{
    public static int $now = 0;

    public static function tick(): void
    {
        self::$now++;
    }
}

/**
 * Provided, don't change: a slow task. It must run inside a Fiber: it
 * suspends until $ms ticks have passed, then returns $ms.
 */
function task(int $ms): int
{
    $doneAt = Clock::$now + $ms;
    while (Clock::$now < $doneAt) {
        Fiber::suspend();
    }
    return $ms;
}

"#;

fn str_lit(s: &str) -> String {
    format!("\"{}\"", escape(s, hex_escape, &[('$', "\\$")]))
}

fn phpdoc(ty: &Type) -> String {
    match ty {
        Type::Int => "int".into(),
        Type::Bool => "bool".into(),
        Type::Str => "string".into(),
        Type::List(t) => format!("list<{}>", phpdoc(t)),
        Type::Map(t) => format!("array<string, {}>", phpdoc(t)),
        Type::Named(n) => naming::pascal(n),
        Type::Fn(ps, r) => {
            let ps: Vec<String> = ps.iter().map(phpdoc).collect();
            format!("Closure({}): {}", ps.join(", "), phpdoc(r))
        }
    }
}

impl Php {
    fn params(&self, spec: &Spec, params: &[Param]) -> String {
        params
            .iter()
            .map(|p| format!("{} ${}", self.type_name(spec, &p.ty, true), naming::camel(&p.name)))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn method_sig(&self, spec: &Spec, m: &Method) -> String {
        format!(
            "public function {}({}): {}",
            naming::camel(&m.name),
            self.params(spec, &m.params),
            self.type_name(spec, &m.returns, false)
        )
    }

    fn type_defs(&self, spec: &Spec) -> String {
        let mut s = String::new();
        for d in &spec.types {
            let name = naming::pascal(&d.name);
            match d.kind {
                DefKind::Interface => {
                    s.push_str(&format!("interface {name}\n{{\n"));
                    let sigs: Vec<String> = d.methods.iter().map(|m| format!("    {};\n", self.method_sig(spec, m))).collect();
                    s.push_str(&sigs.join("\n"));
                    s.push_str("}\n\n");
                }
                DefKind::Record | DefKind::Class => {
                    let implements = if d.implements.is_empty() {
                        String::new()
                    } else {
                        let names: Vec<String> = d.implements.iter().map(|i| naming::pascal(i)).collect();
                        format!(" implements {}", names.join(", "))
                    };
                    s.push_str(&format!("final class {name}{implements}\n{{\n    public function __construct(\n"));
                    for f in &d.fields {
                        s.push_str(&format!(
                            "        public readonly {} ${},\n",
                            self.type_name(spec, &f.ty, false),
                            naming::camel(&f.name)
                        ));
                    }
                    s.push_str("    ) {\n    }\n");
                    for m in &d.methods {
                        s.push_str(&format!(
                            "\n    {}\n    {{\n        throw new RuntimeException('{}');\n    }}\n",
                            self.method_sig(spec, m),
                            stub_message(&format!("{name}::{}", naming::camel(&m.name)))
                        ));
                    }
                    s.push_str("}\n\n");
                }
            }
        }
        s
    }

    fn fn_stub(&self, spec: &Spec, f: &Function, namespaced: bool) -> String {
        let mut docblock = doc(" * ", &f.summary);
        docblock.push_str(" *\n");
        for p in &f.params {
            docblock.push_str(&format!(" * @param {} ${}\n", phpdoc(&p.ty), naming::camel(&p.name)));
        }
        docblock.push_str(&format!(" * @return {}\n", phpdoc(&f.returns)));
        if f.fallible {
            docblock.push_str(" * @throws InvalidArgumentException for invalid input\n");
        }
        let exception = if namespaced { "\\RuntimeException" } else { "RuntimeException" };
        format!(
            "/**\n{docblock} */\n{}\n{{\n    throw new {exception}('{}');\n}}\n",
            self.signature(spec, f),
            stub_message(&self.function_name(f))
        )
    }

    fn call(&self, spec: &Spec, f: &Function, input: &[Value]) -> String {
        let path = match &f.module {
            Some(m) => format!("\\{}\\{}", naming::pascal(m), self.function_name(f)),
            None => self.function_name(f),
        };
        format!("{path}({})", render_args(&f.params, input, |v, t| self.literal(spec, v, t)))
    }
}

impl Backend for Php {
    fn id(&self) -> &'static str {
        "php"
    }
    fn name(&self) -> &'static str {
        "PHP"
    }
    fn fence(&self) -> &'static str {
        "php"
    }
    fn tool(&self) -> &'static Tool {
        &TOOL
    }

    fn function_name(&self, f: &Function) -> String {
        naming::camel(&f.name)
    }

    fn type_name(&self, _spec: &Spec, ty: &Type, _param: bool) -> String {
        match ty {
            Type::Int => "int".into(),
            Type::Bool => "bool".into(),
            Type::Str => "string".into(),
            Type::List(_) | Type::Map(_) => "array".into(),
            Type::Named(n) => naming::pascal(n),
            Type::Fn(..) => "Closure".into(),
        }
    }

    fn literal(&self, spec: &Spec, value: &Value, ty: &Type) -> String {
        match (ty, value) {
            (Type::Int, Value::Number(n)) => n.to_string(),
            (Type::Bool, Value::Bool(b)) => b.to_string(),
            (Type::Str, Value::String(s)) => str_lit(s),
            (Type::List(t), Value::Array(items)) => {
                let parts: Vec<String> = items.iter().map(|v| self.literal(spec, v, t)).collect();
                format!("[{}]", parts.join(", "))
            }
            (Type::Map(t), Value::Object(m)) => {
                let parts: Vec<String> =
                    m.iter().map(|(k, v)| format!("{} => {}", str_lit(k), self.literal(spec, v, t))).collect();
                format!("[{}]", parts.join(", "))
            }
            (Type::Named(n), _) => {
                let def = def_of(spec, n, value);
                let args: Vec<String> = field_values(def, value)
                    .into_iter()
                    .map(|(f, v)| format!("{}: {}", naming::camel(&f.name), self.literal(spec, v, &f.ty)))
                    .collect();
                format!("new {}({})", naming::pascal(&def.name), args.join(", "))
            }
            _ => unreachable!("spec values are validated against their types"),
        }
    }

    fn signature(&self, spec: &Spec, f: &Function) -> String {
        format!(
            "function {}({}): {}",
            self.function_name(f),
            self.params(spec, &f.params),
            self.type_name(spec, &f.returns, false)
        )
    }

    fn stub_path(&self, spec: &Spec) -> PathBuf {
        PathBuf::from(&spec.slug).join(format!("{}.php", spec.slug))
    }

    fn module_path(&self, spec: &Spec, module: &str) -> PathBuf {
        PathBuf::from(&spec.slug).join(format!("{}.php", naming::kebab(module)))
    }

    fn stubs(&self, spec: &Spec) -> Vec<(PathBuf, String)> {
        let mut main = String::from("<?php\n\ndeclare(strict_types=1);\n\n");
        if spec.concurrency {
            main.push_str(CLOCK);
        }
        main.push_str(&self.type_defs(spec));
        main.push_str(&self.fn_stub(spec, &spec.main, false));
        let mut out = vec![(self.stub_path(spec), main)];
        for m in spec.modules() {
            let mut s = format!("<?php\n\ndeclare(strict_types=1);\n\nnamespace {};\n", naming::pascal(m));
            for f in spec.helpers.iter().filter(|h| h.module.as_deref() == Some(m)) {
                s.push('\n');
                s.push_str(&self.fn_stub(spec, f, true));
            }
            out.push((self.module_path(spec, m), s));
        }
        out
    }

    fn tests(&self, spec: &Spec) -> Vec<(PathBuf, String)> {
        let mut s = String::from("<?php\n");
        s.push_str(&header("//", spec, &format!("{}.php", spec.slug)));
        s.push_str("\ndeclare(strict_types=1);\n\nrequire __DIR__ . '/../harness.php';\n");
        for m in spec.modules() {
            s.push_str(&format!("require_once __DIR__ . '/{}.php';\n", naming::kebab(m)));
        }
        s.push_str(&format!("require_once __DIR__ . '/{}.php';\n\n$t = new Harness();\n", spec.slug));

        for (f, case) in spec.cases() {
            let name = case_name(case);
            match &case.kind {
                CaseKind::Call { input, outcome } => {
                    let call = self.call(spec, f, input);
                    match outcome {
                        Outcome::Value(v) if spec.concurrency => {
                            let t = timing(input);
                            s.push_str(&format!(
                                "$t->scenario('{name}', function () {{\n    Clock::$now = 0;\n    $got = {call};\n    Harness::expect($got, {}, 'result');\n    $ticks = Clock::$now;\n    Harness::check($ticks >= {}, \"the clock only reached $ticks ticks, but the slowest task needs {}: run every task to completion\");\n    Harness::check($ticks <= {}, \"took $ticks ticks: run the fibers round-robin so it takes about {} ticks, not {}\");\n}});\n",
                                self.literal(spec, v, &f.returns),
                                t.max, t.max, t.max + 1, t.max, t.sum
                            ));
                        }
                        Outcome::Value(v) => s.push_str(&format!(
                            "$t->equals('{name}', fn() => {call}, {});\n",
                            self.literal(spec, v, &f.returns)
                        )),
                        Outcome::Error => s.push_str(&format!("$t->throws('{name}', fn() => {call});\n")),
                    }
                }
                CaseKind::Scenario { create, steps } => {
                    s.push_str(&format!("$t->scenario('{name}', function () {{\n"));
                    for (i, args) in create.iter().enumerate() {
                        s.push_str(&format!("    $v{i} = {};\n", self.call(spec, f, args)));
                    }
                    let Type::Fn(ps, ret) = &f.returns else { unreachable!() };
                    for (n, step) in steps.iter().enumerate() {
                        let args: Vec<String> = step.input.iter().zip(ps).map(|(v, t)| self.literal(spec, v, t)).collect();
                        s.push_str(&format!(
                            "    Harness::expect($v{}({}), {}, '{}');\n",
                            step.on,
                            args.join(", "),
                            self.literal(spec, &step.expected, ret),
                            step_label(n + 1, step.on, create.len())
                        ));
                    }
                    s.push_str("});\n");
                }
            }
        }
        s.push_str("$t->finish();\n");
        vec![(PathBuf::from(&spec.slug).join(format!("{}.test.php", spec.slug)), s)]
    }

    fn shared(&self, _specs: &[Spec]) -> Vec<(PathBuf, String)> {
        vec![(PathBuf::from("harness.php"), HARNESS.to_string())]
    }

    fn command(&self, spec: &Spec, tool: &Found, track_dir: &Path) -> Invocation {
        Invocation::new(&tool.path, track_dir)
            .args([format!("{}/{}.test.php", spec.slug, spec.slug)])
            .timeout(Duration::from_secs(60))
    }

    fn parse_results(&self, output: &str) -> Vec<(usize, bool)> {
        parse_tap(output)
    }

    fn check_tool(&self, tool: &Found) -> Option<String> {
        let (major, minor, _) = parse_version(&tool.version)?;
        (major < 8 || (major == 8 && minor < 1)).then(|| format!("PHP 8.1 or newer is needed (found {})", tool.version))
    }
}
