const HARNESS: &str = r#""""Generated by `learn generate`. A tiny test harness: it prints `ok <name>`
or `not ok <name> - <why>` for every case. Don't edit this file."""

import sys


class Failure(Exception):
    """A failed check inside a scenario."""


def _is_stub(e: BaseException) -> bool:
    return isinstance(e, NotImplementedError) and str(e).startswith("TODO: implement")


def _same(got, expected) -> bool:
    """Equal, and the same kind of value: True isn't 1, a tuple isn't a list."""
    if isinstance(expected, bool) or isinstance(got, bool):
        return type(got) is type(expected) and got == expected
    if isinstance(expected, list):
        return isinstance(got, list) and len(got) == len(expected) and all(_same(g, e) for g, e in zip(got, expected))
    if isinstance(expected, dict):
        return isinstance(got, dict) and got.keys() == expected.keys() and all(_same(got[k], v) for k, v in expected.items())
    if hasattr(expected, "__dict__") and type(expected).__eq__ is object.__eq__:
        # A plain class compares by identity; compare its type and fields instead.
        return type(got) is type(expected) and _same(vars(got), vars(expected))
    return got == expected


def _raised(e: BaseException) -> str:
    if _is_stub(e):
        return f"still the stub: {e}"
    return f"raised {type(e).__name__}: {e}"


class H:
    def __init__(self) -> None:
        self.failed = 0

    def fail(self, name: str, why: str) -> None:
        self.failed += 1
        print(f"not ok {name} - {why}", flush=True)

    def equals(self, name: str, fn, expected) -> None:
        """The call must return `expected`."""
        try:
            got = fn()
        except Exception as e:
            self.fail(name, _raised(e))
            return
        if _same(got, expected):
            print(f"ok {name}", flush=True)
        else:
            self.fail(name, f"expected {expected!r}, got {got!r}")

    def raises(self, name: str, fn, mentions: list[str] = []) -> None:
        """The call must raise an exception whose message contains every text in `mentions`."""
        try:
            got = fn()
        except Exception as e:
            if _is_stub(e):
                self.fail(name, _raised(e))
                return
            message = str(e)
            for part in mentions:
                if part not in message:
                    self.fail(name, f"the error message {message!r} should mention {part!r}")
                    return
            print(f"ok {name}", flush=True)
            return
        self.fail(name, f"expected an exception, got {got!r}")

    def scenario(self, name: str, fn) -> None:
        """A case made of several checks (H.expect, H.check)."""
        try:
            fn()
        except Failure as f:
            self.fail(name, str(f))
            return
        except Exception as e:
            self.fail(name, _raised(e))
            return
        print(f"ok {name}", flush=True)

    @staticmethod
    def expect(actual, expected, what: str) -> None:
        if not _same(actual, expected):
            raise Failure(f"{what}: expected {expected!r}, got {actual!r}")

    @staticmethod
    def check(ok: bool, message: str) -> None:
        if not ok:
            raise Failure(message)

    def finish(self) -> None:
        sys.exit(1 if self.failed else 0)
"#;

